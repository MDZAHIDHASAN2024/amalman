// PUT update status (completed/pending/incompleted) — one at a time, mutual exclusive
router.put('/status/:ruleId', protect, async (req, res) => {
  try {
    const { status } = req.body; // 'completed' | 'pending' | 'incompleted'
    if (!['completed', 'pending', 'incompleted'].includes(status))
      return res.status(400).json({ message: 'Invalid status' });
    await UserRule.findOneAndUpdate(
      { user: req.user._id, rule: req.params.ruleId },
      { status },
      { upsert: true, new: true },
    );
    // Return updated statusMap
    const userRules = await UserRule.find({ user: req.user._id });
    const statusMap = {};
    userRules.forEach((ur) => {
      statusMap[ur.rule.toString()] = ur.status;
    });
    res.json({ statusMap });
  } catch (err) {
    res.status(500).json({ message: err.message });
  }
});

