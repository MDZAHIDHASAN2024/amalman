// GET all rules + statuses for current user
router.get('/', protect, async (req, res) => {
  try {
    const rules = await GeneralRule.find({ user: req.user._id }).sort({
      order: 1,
      createdAt: 1,
    });
    const userRules = await UserRule.find({ user: req.user._id });
    const statusMap = {};
    userRules.forEach((ur) => {
      statusMap[ur.rule.toString()] = ur.status;
    });
    res.json({ rules, statusMap });
  } catch (err) {
    res.status(500).json({ message: err.message });
  }
});

// POST create rule (max 100 manually added rules)
router.post('/', protect, async (req, res) => {
  try {
    const count = await GeneralRule.countDocuments({ user: req.user._id });
    if (count >= 200)
      return res
        .status(400)
        .json({ message: 'সর্বোচ্চ ২০০টি নিয়ম যোগ করা যাবে।' });
    const { text, category } = req.body;
    if (!text) return res.status(400).json({ message: 'নিয়মের বিবরণ দিন।' });
    const rule = await GeneralRule.create({
      user: req.user._id,
      text,
      category: category || 'সাধারণ',
      order: count,
    });
    res.status(201).json(rule);
  } catch (err) {
    res.status(500).json({ message: err.message });
  }
});

// POST seed default rules — no 100 limit, seeds all rules
router.post('/seed', protect, async (req, res) => {
  try {
    const existing = await GeneralRule.countDocuments({ user: req.user._id });
    const existingTexts =
      existing > 0
        ? (
            await GeneralRule.find({ user: req.user._id }).select('text').lean()
          ).map((r) => r.text)
        : [];
    const toInsert = SEED_RULES.filter(
      (r) => !existingTexts.includes(r.text),
    ).map((r, i) => ({ ...r, user: req.user._id, order: existing + i }));
    if (toInsert.length === 0)
      return res.status(400).json({ message: 'সব নিয়ম ইতিমধ্যে যোগ আছে।' });
    await GeneralRule.insertMany(toInsert);
    const rules = await GeneralRule.find({ user: req.user._id }).sort({
      order: 1,
    });
    res.json({ rules, added: toInsert.length });
  } catch (err) {
    res.status(500).json({ message: err.message });
  }
});

